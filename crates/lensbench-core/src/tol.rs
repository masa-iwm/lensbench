//! 名前の付いた判定の閾値。同じ意味の判定は同じ定数を使う（値の理由もここに書く）。

/// 理想レンズ（薄肉の近軸レンズ）の物点・像点の距離 [mm] がこれを超える（か無限大）なら無限遠とみなす。
/// 1/z が丸めの桁（f が 1〜1000 mm で 1e-12 / f ほど）に埋もれる距離
pub const INFINITE_DIST: f64 = 1e12;

/// 理想レンズの物点・像点の距離 z が無限遠か（[`INFINITE_DIST`]）
#[inline]
pub fn infinite_dist(z: f64) -> bool {
    !z.is_finite() || z.abs() > INFINITE_DIST
}

/// 射出瞳の位置 [mm] がこれより遠い（か無限大）なら、OPD の基準を参照球でなく主光線に垂直な平面にする
/// （半径 1e9 mm の球と平面の差は瞳の径 100 mm で 1e-6 mm ほどで、球の交点の計算の丸めの方が大きくなる）
pub const EXPP_FAR: f64 = 1e9;

/// 開口の判定の余裕 [mm]: 交点が縁からこれ以内なら内側とみなす（縁の上に狙った光線、たとえば周辺光線が丸めで
/// けられないように）。遮蔽・輪帯の内径は内側へ同じだけ広げる。楕円は正規化した半径²に足す
pub const APERTURE_EDGE: f64 = 1e-9;

/// 光線の狙い（エイミング）のニュートン法の収束の許容差（目標の大きさ max(|t|, 1) に対する比）
pub const AIM_TOL: f64 = 1e-12;

/// 光線の狙いが届かなかったとみなす残差（目標の大きさ max(|t|, 1) に対する比）。[`AIM_TOL`] まで収束しなくても、
/// これ以内なら届いたものとして使う
pub const AIM_FAIL: f64 = 1e-9;

/// 光線の狙いの差分ヤコビアンの刻み（瞳・物体の座標の大きさ max(|v|, 1) に対する比）
pub const AIM_STEP: f64 = 1e-7;

/// 光線の狙いの直線探索で、残差が有限になるまで歩幅を半分にしていき、これより小さくなったら諦める（ニュートン法の 1 歩に対する比）
pub const AIM_LINE_MIN: f64 = 1e-6;

/// 単位ベクトルの向きが揃っている（平行・反平行）とみなす大きさ: 外積 |a × b|、または a の k に垂直な成分の長さが
/// これ以下なら、偏光の基底（s 偏光の向きなど）をその 2 本から作らずに別の決め方にする（丸めで向きが定まらないため）
pub const PARALLEL_SIN: f64 = 1e-12;

/// 交点のニュートン法を止める刻みの下限 [mm]（`trace::newton_tol` とまとめた追跡で同じ）。実際の刻みはこれと距離 s・
/// 矢高 z の丸め（8 ulp）の大きい方
pub const NEWTON_STEP_MIN: f64 = 1e-14;

/// 開口の速い判定で、半径の 2 乗が境界の 2 乗からこの比より離れていればそれで内外を決める（半径の 2 乗の丸めの
/// 誤差、数 ulp より十分大きい幅）。境界の近くは hypot で決め直すので、結果は hypot の判定と同じ
pub const RADIUS2_MARGIN: f64 = 1e-12;

/// 正規化した瞳の単位円の縁の余裕: x² + y² ≤ 1 + これ なら内側（丸めで縁の点を落とさない）
pub const PUPIL_RIM: f64 = 1e-12;

/// 像側の瞳の縮尺 J（瞳の座標に対する方向余弦の微分）の対角がこれ以下なら、像空間の開口が 0（アフォーカルなど）
/// とみなして MTF を求めない
pub const JACOBIAN_MIN: f64 = 1e-12;

/// 瞳の縮尺 J を対角・等方とみなす比: 非対角（と x・y の差）が対角のこの比以下なら丸めの差として扱う
pub const JACOBIAN_REL: f64 = 1e-12;
